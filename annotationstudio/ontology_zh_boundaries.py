def correct_retained_chinese_boundaries(label_info):
    """Repair translations only; saved projects are not mutated by this helper."""
    for (category, name), spec in label_info.items():
        if name == 'Unlabeled':
            spec['boundary_rule_zh'] = (
                '编辑时保留暂定区间或时间点；在接收前选择有意义的标签，'
                '包括适用时的明确不确定性标签。')
        elif spec['boundary_rule'] in _COMMON_TRANSLATIONS:
            spec['boundary_rule_zh'] = _COMMON_TRANSLATIONS[spec['boundary_rule']]
